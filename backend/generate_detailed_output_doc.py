    Base.metadata.drop_all(bind=engine)
    Base.metadata.create_all(bind=engine)
    db = SessionLocal()
    
    doc = ["# Complete Detailed Output Document: TeamForge AI RAD Prototype\n"]
    doc.append("This document contains the exact detailed outputs generated by every engine in the TeamForge AI lifecycle for a real-world scenario.\n")
    
    # 1. TEAM CREATION
    doc.append("## 1. Team Hub & Onboarding Output")
    lead_in = UserRegister(name="Maya Patel", email="maya@demo.com", password="pwd")
    lead = auth_team_service.register_user(db, lead_in)
    team = auth_team_service.create_team(db, TeamCreate(name="EventForge Squad"), lead.id)
    doc.append(f"**Team Created:** {team.name} (Invite Code: {team.team_code})")
    
    dev1_in = UserRegister(name="Liam Vance", email="liam@demo.com", password="pwd")
    dev1 = auth_team_service.register_user(db, dev1_in)
    
    dev2_in = UserRegister(name="Ethan Cole", email="ethan@demo.com", password="pwd")
    dev2 = auth_team_service.register_user(db, dev2_in)

    dev3_in = UserRegister(name="Chloe Bennett", email="chloe@demo.com", password="pwd")
    dev3 = auth_team_service.register_user(db, dev3_in)

    m_dev1 = user_team.TeamMember(user_id=dev1.id, team_id=team.id, role="developer")
    m_dev2 = user_team.TeamMember(user_id=dev2.id, team_id=team.id, role="developer")
    m_dev3 = user_team.TeamMember(user_id=dev3.id, team_id=team.id, role="ai_assisted")
    db.add_all([m_dev1, m_dev2, m_dev3])
    db.commit()
    db.refresh(m_dev1)
    db.refresh(m_dev2)
    db.refresh(m_dev3)

    m_lead = db.query(user_team.TeamMember).filter(user_team.TeamMember.user_id == lead.id).first()

    db.add_all([
        user_team.MemberSkill(member_id=m_lead.id, name="Python", level="Advanced"),
        user_team.MemberSkill(member_id=m_dev1.id, name="React", level="Advanced"),
        user_team.MemberSkill(member_id=m_dev2.id, name="SQL", level="Advanced"),
        user_team.MemberSkill(member_id=m_dev3.id, name="FastAPI", level="Advanced"),
        user_team.MemberSubscription(member_id=m_dev1.id, tool_name="Figma Pro", tier="Pro"),
        user_team.MemberSubscription(member_id=m_dev3.id, tool_name="Cursor Pro", tier="Pro")
    ])
    db.commit()
    
    # 2. PS EVALUATION
    doc.append("## 2. Problem Statement Ranking Engine Output")
    ps1 = CandidatePSInput(id="ps-1", title="Campus Event Booking Platform", problem_statement="Overselling tickets.", proposed_idea="FastAPI+React event booking.", target_sponsor_track="Stripe")
    ps2 = CandidatePSInput(id="ps-2", title="Zero-Knowledge Medical Ledger", problem_statement="Privacy.", proposed_idea="Custom blockchain.", target_sponsor_track=None)
    eval_req = PSEvaluateRequest(team_id=team.id, time_budget_hours=48, candidate_problem_statements=[ps1, ps2])
    eval_res = ps_analyzer_engine.evaluate_multiple_problem_statements(db, eval_req)
    doc.append("### Winning Problem Statement Breakdown")
    doc.append("`json\n" + json.dumps(eval_res.top_recommended_ps.model_dump(), indent=2) + "\n`\n")
    
    # 3. PROJECT CREATION & FEASIBILITY
    doc.append("## 3. Project Feasibility Engine Output")
    proj_in = ProjectCreate(
        team_id=team.id, name="Campus Event Booking Platform",
        problem_statement="Event organizers struggle with ticket overselling and slow check-ins.", 
        idea="FastAPI + React event booking platform with real-time seat locks and QR ticket passes.",
        time_budget=TimeBudgetSchema(value=48, unit="hours"),
        mandatory_platforms=["Stripe", "Vercel"]
    )
    proj = project_service.create_project(db, proj_in)
    feasibility = project_service.analyze_project_feasibility(db, proj.id)
    doc.append("### Feasibility Assessment (JSON Response)")
    doc.append("`json\n" + json.dumps(feasibility.model_dump(), indent=2) + "\n`\n")

    # Now we can get hub status
    hub_status = auth_team_service.get_team_hub_status(db, proj.id)
    doc.append("### Initial Team Hub Status (JSON Response)")
    doc.append("`json\n" + json.dumps(hub_status.model_dump(), indent=2) + "\n`\n")


