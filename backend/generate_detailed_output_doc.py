    doc.append("## 4. Architecture & SDLC Decision Engine Output")
    sdlc = sdlc_engine.recommend_sdlc_model(db, proj.id)
    arch = arch_engine.recommend_architecture(db, proj.id)
    doc.append("### Architecture Recommendation (JSON Response)")
    doc.append("`json\n" + json.dumps({"tier": arch.tier, "components": arch.components}, indent=2) + "\n`\n")
    
    arch_engine.accept_architecture(db, proj.id, arch.id)

