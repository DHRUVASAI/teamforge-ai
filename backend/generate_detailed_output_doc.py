    doc.append("### Task Decomposition Graph Summary")
    doc.append(f"**Total Tasks Generated:** {len(task_res.tasks)}")
    doc.append(f"**Critical Path Bottlenecks:** {len(task_res.bottlenecks)}")
    
    # Make some tasks depend on others to show actionable blockers
    tasks_objs = db.query(task.Task).filter(task.Task.project_id == proj.id).all()
    if len(tasks_objs) >= 2:
        tasks_objs[1].depends_on = [tasks_objs[0].id]
        tasks_objs[0].assignment = task.TaskAssignment(member_id=m_dev2.id, reasoning="best fit")
        tasks_objs[1].assignment = task.TaskAssignment(member_id=m_dev1.id, reasoning="best fit")
        db.commit()

    hub_status2 = auth_team_service.get_team_hub_status(db, proj.id)
    doc.append("### Team Hub Actionable Blocker Status (JSON)")
    doc.append("`json\n" + json.dumps(hub_status2.model_dump(), indent=2) + "\n`\n")

    doc.append("### Sample Task Record (JSON)")
    if tasks_objs:
        t_dict = {
            "title": tasks_objs[0].title, "status": tasks_objs[0].status,
            "dependencies": tasks_objs[0].depends_on, "assignee_id": tasks_objs[0].assignment.member_id if tasks_objs[0].assignment else None
        }
        doc.append("`json\n" + json.dumps(t_dict, indent=2) + "\n`\n")

